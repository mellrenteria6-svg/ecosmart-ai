// JPEG mínimo con estructura válida (SOI, APP0, SOF0, SOS, EOI) para las pruebas automáticas.
// No es una foto real: solo sirve para comprobar que el servidor acepta lo bien formado (RNF04).
export function jpegDePrueba(ancho = 64, alto = 48, relleno = 200): string {
  const sof = [0xff, 0xc0, 0x00, 0x11, 0x08, alto >> 8, alto & 0xff, ancho >> 8, ancho & 0xff, 0x03, 0x01, 0x22, 0x00, 0x02, 0x11, 0x01, 0x03, 0x11, 0x01]
  const bytes = Buffer.from([
    0xff, 0xd8, // SOI
    0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, // APP0 (JFIF)
    ...sof,
    0xff, 0xda, 0x00, 0x0c, 0x03, 0x01, 0x00, 0x02, 0x11, 0x03, 0x11, 0x00, 0x3f, 0x00, // SOS
    ...Array.from({ length: relleno }, (_, i) => (i * 37) % 0xfe), // "datos" de imagen sin 0xFF
    0xff, 0xd9, // EOI
  ])
  return 'data:image/jpeg;base64,' + bytes.toString('base64')
}
